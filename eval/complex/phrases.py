def say(locale: str, parts: tuple[tuple[str, Mapping[str, object]], ...]) -> str:
    """One user message: each phrase in ``locale`` with its parameters, joined by spaces.

    A parameter value is either one string for every language or a mapping from locale to string.
    """
    index = LOCALES.index(locale)
    rendered = []
    for name, params in parts:
        values = {key: value[locale] if isinstance(value, Mapping) else value for key, value in params.items()}
        rendered.append(P[name][index].format(**values))
    return " ".join(rendered)
