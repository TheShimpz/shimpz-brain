"""The first precision-v3 panel: 48 independent complex-task templates, eight per stratum (ADR-0094).

Each template is one task cluster: its scripted user turns, an independently written reference workflow per turn
(the Actions a correct agent runs, written from the task, never generated by a solver), its fault schedule, and what
each turn must convey. Languages and parameter values are instances of a template, not new clusters. Episode lengths
follow 10 / 17 / 14 / 7 templates of 1-2, 3-6, 7-15, and 16-40 user turns; compositions are near-equal across and,
chain, selection, and mixed. This module uses only the standard library.
"""

